#!/usr/bin/env python3
"""Build the footer from the LIVE served capture.

Law 0: the port copies the served design. Hand-retyping icon paths and copy is how fidelity
dies, so this transforms the captured bytes instead:
  - internal absolute URLs (https://gwillchijioke.qzz.io/...) -> '%BASE%/...' placeholder,
    substituted at build time so the GitHub Pages subpath works
  - external URLs (github.com, gwillchijioke.com, ...) stay absolute
  - WP-only nonce attrs are dropped; nothing visual changes

Outputs:
  src/data/footer-html.ts   the markup as an exported string
  src/components/Footer.astro  thin renderer
"""
import re

SRC = "/home/opc/work/tech-truth/footer-truth.html"
TS = "/home/opc/work/tech-astro/src/data/footer-html.ts"
ASTRO = "/home/opc/work/tech-astro/src/components/Footer.astro"

html = open(SRC, encoding="utf-8", errors="replace").read().strip()
html = re.sub(r'\s*nonce="[^"]*"', "", html)

# Internal origin -> base placeholder.
html = html.replace('href="https://gwillchijioke.qzz.io/', 'href="%BASE%/')
html = html.replace('src="https://gwillchijioke.qzz.io/', 'src="%BASE%/')
html = html.replace('href="https://gwillchijioke.qzz.io"', 'href="%BASE%/"')

leftover = re.findall(r'https://gwillchijioke\.qzz\.io[^"\s]*', html)
if leftover:
    print("WARN leftover self-origin refs:", leftover[:5])

# Escape for a JS template literal.
esc = html.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${")

open(TS, "w", encoding="utf-8").write(
    "// GENERATED by scripts/gen-footer.py from tech-truth/footer-truth.html — do not hand-edit.\n"
    "// %BASE% is substituted at build time.\n"
    f"export const FOOTER_HTML = `{esc}`;\n"
)

open(ASTRO, "w", encoding="utf-8").write(
    """---
// Footer — generated. Markup lives in src/data/footer-html.ts, transcribed from the LIVE
// served capture so icon paths, copy and class names stay byte-faithful.
// Regenerate with: python3 scripts/gen-footer.py
import { BASE } from '../lib/url';
import { FOOTER_HTML } from '../data/footer-html';
const html = FOOTER_HTML.replaceAll('%BASE%', BASE);
---

<Fragment set:html={html} />
"""
)

print(f"wrote {TS} ({len(html)} bytes) and {ASTRO}")
