
(function(){
'use strict';
function $(id){return document.getElementById(id);}
var preview=$('preview'), byteCount=$('byteCount');
var copyBtn=$('copyBtn'), dlBtn=$('dlBtn');
var currentText='';

function chk(id){var el=$(id);return !!(el&&el.checked);}
function val(id){var el=$(id);return el?el.value:'';}
function escRe(s){return String(s).replace(/[.*+?^${}()|[\]\\]/g,'\\$&');}
function normDomain(s){
  s=String(s||'').trim().toLowerCase();
  s=s.replace(/^https?:\/\//,'');
  s=s.replace(/\/.*$/,'');
  s=s.replace(/^www\./,'');
  s=s.replace(/\/+$/,'');
  return s;
}
function normIp(s){
  s=String(s||'').trim();
  // handle CIDR and exact
  return s.replace(/\/\d+$/,'');
}
function splitLines(v){return String(v||'').split(/\r?\n/).map(function(x){return x.trim();}).filter(Boolean);}
function splitDomains(v){
  // split on newlines AND commas, then normalise + dedupe
  var out=[];
  splitLines(v).forEach(function(line){
    String(line).split(/,/).forEach(function(part){
      var d=normDomain(part);
      if(d && out.indexOf(d)<0)out.push(d);
    });
  });
  return out;
}

function build(){
  var date=new Date().toISOString().slice(0,10);
  var L=[];
  L.push('# WordPress .htaccess - generated by ht·min (GWill)');
  L.push('# date: '+date+'  ·  safe to re-run through the generator');
  L.push('# Everything is intentional and machine-generated. Apache 2.4 syntax (Require).');
  L.push('#');

  /* ---------- rewrite section (single RewriteEngine On, before all custom rules) ---------- */
  var rew=[];
  var needRewrite=false;

  // Redirects (canonical) - top of rewrite section
  var redirectUnused=0;
  if(chk('red_https')){
    needRewrite=true;
    rew.push('# BEGIN GWill - Redirects: force HTTPS - '+date);
    rew.push('RewriteCond %{HTTPS} off');
    rew.push('RewriteRule ^(.*)$ https://%{HTTP_HOST}%{REQUEST_URI} [L,R=301]');
    rew.push('# END GWill - Redirects: force HTTPS');
    rew.push('');
  }
  if(chk('red_www')){
    needRewrite=true;
    var m=val('www_mode');
    rew.push('# BEGIN GWill - Redirects: '+(m==='add'?'add www':'remove www')+' - '+date);
    if(m==='add'){
      rew.push('RewriteCond %{HTTP_HOST} !^www\\. [NC]');
      rew.push('RewriteRule ^(.*)$ https://www.%{HTTP_HOST}%{REQUEST_URI} [L,R=301]');
    }else{
      rew.push('RewriteCond %{HTTP_HOST} ^www\\.(.*)$ [NC]');
      rew.push('RewriteRule ^(.*)$ https://%1%{REQUEST_URI} [L,R=301]');
    }
    rew.push('# END GWill - Redirects: www canonical');
    rew.push('');
  }
  if(chk('red_slash')){
    needRewrite=true;
    var sm=val('slash_mode');
    rew.push('# BEGIN GWill - Redirects: '+(sm==='add'?'add trailing slash':'remove trailing slash')+' - '+date);
    rew.push('RewriteCond %{REQUEST_FILENAME} !-f');
    rew.push('RewriteCond %{REQUEST_FILENAME} !-d');
    if(sm==='add'){
      rew.push('RewriteCond %{REQUEST_URI} !/$');
      rew.push('RewriteRule ^(.*)$ $1/ [L,R=301]');
    }else{
      rew.push('RewriteCond %{REQUEST_URI} /$');
      rew.push('RewriteRule ^(.*)/$ $1 [L,R=301]');
    }
    rew.push('# END GWill - Redirects: trailing slash');
    rew.push('');
  }

  // Hotlink (R3)
  if(chk('hot_enable')){
    needRewrite=true;
    var domains=[];
    var own=normDomain(val('hot_domain'));
    if(own)domains.push(own);
    splitDomains(val('hot_domains')).forEach(function(d){ if(domains.indexOf(d)<0)domains.push(d); });
    rew.push('# BEGIN GWill - Hotlink protection - '+date);
    if(domains.length){
      if(chk('hot_empty')) rew.push('RewriteCond %{HTTP_REFERER} !^$');
      domains.forEach(function(d){ rew.push('RewriteCond %{HTTP_REFERER} !^https?://([^/]+\\.)*'+escRe(d)+'(/|$) [NC]'); });
      rew.push('RewriteRule \\.(jpg|jpeg|png|gif|webp|svg|bmp)$ - [F,NC,L]');
    }else{
      rew.push('# (no domains supplied - hotlink protection added no rules; add your site domain to enable)');
    }
    rew.push('# END GWill - Hotlink protection');
    rew.push('');
  }

  // XML-RPC soft block (R2)
  if(chk('sec_xmlrpc')){
    needRewrite=true;
    rew.push('# BEGIN GWill - Block XML-RPC - '+date);
    rew.push('# Note: this breaks Jetpack and any app that uses XML-RPC.');
    rew.push('RewriteCond %{REQUEST_URI} ^/xmlrpc\\.php$ [NC]');
    rew.push('RewriteRule ^ - [F,L]');
    rew.push('# END GWill - Block XML-RPC');
    rew.push('');
  }

  // Login IP allowlist (R2)
  if(chk('login_ip')){
    var ips=splitLines(val('login_ips')).map(function(l){return l.split(/\s+/)[0];}).filter(Boolean);
    if(ips.length){
      needRewrite=true;
      rew.push('# BEGIN GWill - Login IP allowlist - '+date);
      rew.push('# Only your own static IPs. A dynamic residential IP WILL lock you out.');
      rew.push('RewriteCond %{REQUEST_URI} ^/wp-login\\.php(/|$) [NC]');
      ips.forEach(function(ip){ rew.push('RewriteCond %{REMOTE_ADDR} !^'+escRe(normIp(ip))+'$'); });
      rew.push('RewriteRule ^ - [F,L]');
      rew.push('# END GWill - Login IP allowlist');
      rew.push('');
    }
  }

  // Uploads PHP execution disable (R2) - scoped, inside rewrite (R1-safe)
  if(chk('sec_uploads')){
    needRewrite=true;
    rew.push('# BEGIN GWill - No PHP in uploads - '+date);
    rew.push('# Scoped to wp-content/uploads only; theme/plugin PHP is untouched.');
    rew.push('# (A bare <FilesMatch "\\.php$"> would not scope to a subdir from the root - a path RewriteRule is the correct, safe way.)');
    rew.push('RewriteRule ^wp-content/uploads/.*\\.php$ - [F,L,NC]');
    rew.push('# END GWill - No PHP in uploads');
    rew.push('');
  }

  // SQLite DB dir deny (R4)
  if(chk('sql_dbdir')){
    needRewrite=true;
    rew.push('# BEGIN GWill - SQLite-WP: deny /wp-content/database/ - '+date);
    rew.push('# The SQLite DB (the entire site database) lives here. 403 it.');
    rew.push('RewriteRule ^wp-content/database/ - [F,L]');
    rew.push('# END GWill - SQLite-WP: deny database dir');
    rew.push('');
  }

  // The WP permalink block needs mod_rewrite even with no custom rules selected.
  // Emit ONE <IfModule mod_rewrite.c> with a single RewriteEngine On, put the
  // custom rules first, then the preserved WordPress permalink rules (R1 order).
  L.push('# BEGIN GWill - Custom rewrite rules - '+date);
  L.push('<IfModule mod_rewrite.c>');
  L.push('RewriteEngine On');
  L.push('');
  while(rew.length && rew[0]==='')rew.shift();
  L.push(rew.join('\n').replace(/[ \t]+$/gm,''));
  L.push('');
  // preserved WordPress permalink block - same <IfModule>, no duplicate RewriteEngine On
  L.push('# BEGIN WordPress');
  L.push('RewriteRule .* - [E=HTTP_AUTHORIZATION:%{HTTP:Authorization}]');
  L.push('RewriteBase /');
  L.push('RewriteRule ^index\\.php$ - [L]');
  L.push('RewriteCond %{REQUEST_FILENAME} !-f');
  L.push('RewriteCond %{REQUEST_FILENAME} !-d');
  L.push('RewriteRule . /index.php [L]');
  L.push('# END WordPress');
  L.push('</IfModule>');
  L.push('# END GWill - Custom rewrite rules');
  L.push('');

  /* ---------- non-rewrite guarded blocks ---------- */
  function block(feature, inner){
    L.push('# BEGIN GWill - '+feature+' - '+date);
    L.push(inner.join('\n').replace(/[ \t]+$/gm,''));
    L.push('# END GWill - '+feature);
    L.push('');
  }

  // Security headers (mod_headers)
  if(chk('sec_headers')){
    block('Security: HTTP headers',[
      '<IfModule mod_headers.c>',
      'Header set X-Content-Type-Options "nosniff"',
      'Header set X-Frame-Options "SAMEORIGIN"',
      'Header set Referrer-Policy "strict-origin-when-cross-origin"',
      'Header set X-XSS-Protection "1; mode=block"',
      'Header set Permissions-Policy "geolocation=(), microphone=(), camera=(), payment=()"',
      '</IfModule>'
    ]);
  }

  // Server signature
  if(chk('sec_sig')){
    block('Security: hide server signature',[
      'ServerSignature Off',
      'ServerTokens Prod'
    ]);
  }

  // Dotfiles
  if(chk('sec_dotfiles')){
    block('Security: block hidden dotfiles',[
      '<FilesMatch "^\\.(htaccess|htpasswd|git|env|user\\.ini|svn)$">',
      '  Require all denied',
      '</FilesMatch>'
    ]);
  }

  // Browser caching (mod_expires)
  if(chk('cache_expires')){
    block('Caching: browser cache (mod_expires)',[
      '<IfModule mod_expires.c>',
      '  ExpiresActive On',
      '  ExpiresByType image/jpeg "access plus 1 year"',
      '  ExpiresByType image/png "access plus 1 year"',
      '  ExpiresByType image/webp "access plus 1 year"',
      '  ExpiresByType image/svg+xml "access plus 1 year"',
      '  ExpiresByType image/gif "access plus 1 year"',
      '  ExpiresByType text/css "access plus 1 month"',
      '  ExpiresByType application/javascript "access plus 1 month"',
      '  ExpiresByType text/javascript "access plus 1 month"',
      '  ExpiresByType font/woff2 "access plus 1 year"',
      '  ExpiresByType font/woff "access plus 1 year"',
      '</IfModule>'
    ]);
  }

  // Cache-Control (mod_headers)
  if(chk('cache_hdrs')){
    block('Caching: static asset Cache-Control (mod_headers)',[
      '<IfModule mod_headers.c>',
      '  <FilesMatch "\\.(jpg|jpeg|png|webp|gif|svg|css|js|woff2?)$">',
      '    Header set Cache-Control "public, max-age=31536000, immutable"',
      '  </FilesMatch>',
      '</IfModule>'
    ]);
  }

  // Gzip (mod_deflate)
  if(chk('cache_gzip')){
    block('Caching: gzip / deflate (mod_deflate)',[
      '<IfModule mod_deflate.c>',
      '  AddOutputFilterByType DEFLATE text/plain text/html text/xml text/css text/javascript application/javascript application/json application/xml image/svg+xml',
      '</IfModule>'
    ]);
  }

  // SQLite files (R4)
  if(chk('sql_files')){
    block('SQLite-WP: block DB file extensions',[
      '<FilesMatch "\\.(sqlite|sqlite3|db|sql)$">',
      '  Require all denied',
      '</FilesMatch>'
    ]);
  }

  // wp-config.php (R4)
  if(chk('sql_wp_cfg')){
    block('SQLite-WP: protect wp-config.php (Apache 2.4)',[
      '<FilesMatch "^wp-config\\.php$">',
      '  Require all denied',
      '</FilesMatch>',
      '# On Apache 2.2 replace the above with: Order allow,deny / Deny from all'
    ]);
  }

  // Options -Indexes (R4)
  if(chk('sql_indexes')){
    block('SQLite-WP: disable directory listings',[
      'Options -Indexes'
    ]);
  }

  /* ---------- custom redirects (non-rewrite, plain Redirect directives) ---------- */
  if(chk('red_custom')){
    var custom=[];
    splitLines(val('custom_rules')).forEach(function(line){
      if(line.charAt(0)==='#')return;
      var parts=line.split(/\s+/);
      if(parts.length<2)return;
      if(/^\d{3}$/.test(parts[0])){ // status + from + to
        custom.push('Redirect '+parts[0]+' '+parts[1]+' '+parts[2]);
      }else{
        custom.push('Redirect 301 '+parts[0]+' '+parts[1]);
      }
    });
    if(custom.length){
      L.push('# BEGIN GWill - Redirects: custom - '+date);
      custom.forEach(function(c){ L.push(c); });
      L.push('# END GWill - Redirects: custom');
      L.push('');
    }
  }

  // trim trailing blank lines
  while(L.length && L[L.length-1]==='')L.pop();
  return L.join('\n')+'\n';
}

/* ---------- render preview with comment/directive coloring ---------- */
function escapeHtml(s){return String(s).replace(/[&<>]/g,function(c){return {'&':'&amp;','<':'&lt;','>':'&gt;'}[c];});}
function render(txt){
  currentText=txt;
  window.__ht_text=txt; // expose the raw authorized text for tests / copy verification
  var lines=txt.split('\n');
  var html='';
  for(var i=0;i<lines.length;i++){
    var line=lines[i];
    var t=line.trim();
    if(t===''){ html+='<code>&nbsp;</code>\n'; continue; }
    if(t.charAt(0)==='#'){ html+='<code class="cmt">'+escapeHtml(line)+'</code>\n'; continue; }
    var esc=escapeHtml(line);
    var kwMatch=line.match(/^(\s*)([A-Za-z][A-Za-z0-9_]*)/);
    var out=esc;
    if(kwMatch){
      var kw=kwMatch[2];
      var isTag=(t.indexOf('<IfModule')===0||t.indexOf('</IfModule')===0);
      var isBoxed=(t.indexOf('FilesMatch')>=0||t.indexOf('RewriteRule')===0||t.indexOf('Require')===0||t.indexOf('Options')===0);
      if(isTag){
        out=esc.replace(/<IfModule[^>]*>|<\/IfModule>/g,function(x){return '<span class="tag">'+x+'</span>';});
      }else if(isBoxed){
        var first=kw.length?kw:'';
        out=esc.replace(new RegExp('^('+escRe(first)+')'),'<span class="kw">$1</span>');
      }
    }
    html+='<code>'+out+'</code>\n';   // trailing \n keeps textContent newline-separated
  }
  preview.innerHTML=html;
  byteCount.textContent=String(txt.length)+' B';
}
function update(){
  render(build());
  // login warning + panel visibility
  var loginOn=chk('login_ip');
  $('panel_login').hidden=!loginOn;
  $('login_warn').hidden=!(loginOn && val('login_ips').trim());
  $('panel_hot').hidden=!chk('hot_enable');
  $('panel_www').hidden=!chk('red_www');
  $('panel_slash').hidden=!chk('red_slash');
  $('panel_custom').hidden=!chk('red_custom');
  // highlight active option cards
  Array.prototype.forEach.call(document.querySelectorAll('#htapp .opt[data-opt]'),function(o){
    var id=o.getAttribute('data-opt');
    if(id==='hot_empty'||id==='login_ip')return;
    var el=$(id);
    if(el)o.setAttribute('data-on',el.checked?'1':'0');
  });
  // login card active state
  $('login_ip').closest('.opt').setAttribute('data-on',chk('login_ip')?'1':'0');
  $('hot_enable').closest('.opt').setAttribute('data-on',chk('hot_enable')?'1':'0');
}

/* ---------- copy / download ---------- */
function copyText(t){
  if(navigator.clipboard&&navigator.clipboard.writeText){
    navigator.clipboard.writeText(t).then(function(){flash(copyBtn,'Copied ✓');},function(){fallbackCopy(t);});
  }else fallbackCopy(t);
}
function fallbackCopy(t){
  var ta=document.createElement('textarea');ta.value=t;ta.style.position='fixed';ta.style.opacity='0';document.body.appendChild(ta);
  ta.focus();ta.select();
  try{document.execCommand('copy');flash(copyBtn,'Copied ✓');}catch(e){flash(copyBtn,'copy failed','err');}
  document.body.removeChild(ta);
}
function flash(btn,label){
  var old=btn.textContent;btn.textContent=label;setTimeout(function(){btn.textContent=old;},1400);
}
function download(){
  var blob=new Blob([currentText],{type:'text/plain'});
  var url=URL.createObjectURL(blob);
  var a=document.createElement('a');a.href=url;a.download='.htaccess';document.body.appendChild(a);a.click();
  setTimeout(function(){URL.revokeObjectURL(url);a.remove();},400);
}

/* ---------- events: any change re-renders ---------- */
function bind(){
  Array.prototype.forEach.call(document.querySelectorAll('#htapp .opt input[type=checkbox], #htapp select'),function(el){
    el.addEventListener('change',update);
  });
  var deb=null;
  Array.prototype.forEach.call(document.querySelectorAll('#htapp input[type=text], #htapp textarea'),function(el){
    el.addEventListener('input',function(){ if(deb)clearTimeout(deb); deb=setTimeout(update,160); });
  });
  copyBtn.addEventListener('click',function(){copyText(currentText);});
  dlBtn.addEventListener('click',download);
}
bind();
update();
})();
