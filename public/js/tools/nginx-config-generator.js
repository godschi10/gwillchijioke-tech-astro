
(function(){
'use strict';
function $(id){return document.getElementById(id);}
var preview=$('preview'), byteCount=$('byteCount'), copyBtn=$('copyBtn'), dlBtn=$('dlBtn');
var currentText='';

function gv(id){var el=$(id);return el?el.value.trim():'';}
function chk(id){var el=$(id);return !!(el&&el.checked);}
function preset(){var el=document.querySelector('input[name="preset"]:checked');return el?el.value:'free';}
function escRe(s){return String(s).replace(/[.*+?^${}()|[\]\\]/g,'\\$&');}

/* ---- preset tuning knobs ---- */
function presetValues(){
  var p=preset();
  if(p==='free'){
    return {workerConn:1024, cpuWorkers:'comment', // commented: worker_processes auto
      fcgiTimeout:30, cacheZone:'10m', cacheMaxSize:'100m', cacheInactive:'60m',
      gzipOn:true, note:'free-tier'};
  }
  if(p==='std'){
    return {workerConn:2048, cpuWorkers:'auto', fcgiTimeout:60, cacheZone:'20m', cacheMaxSize:'200m', cacheInactive:'60m',
      gzipOn:true, note:'standard'};
  }
  return {workerConn:4096, cpuWorkers:'auto', fcgiTimeout:120, cacheZone:'30m', cacheMaxSize:'300m', cacheInactive:'90m',
    gzipOn:true, note:'performance'};
}

function build(){
  var date=new Date().toISOString().slice(0,10);
  var pv=presetValues();
  var msgEl=$('ngx-msg');
  function inputError(t){ if(msgEl){ msgEl.textContent=t; msgEl.hidden=false; } }
  function clearInputError(){ if(msgEl){ msgEl.hidden=true; msgEl.textContent=''; } }
  var hostRaw=gv('server_name').trim();
  var HOST_RE=/^(?=.{1,253}$)([a-z0-9]([a-z0-9-]{0,61}[a-z0-9])?\.)*[a-z]{2,}$/i;
  var SOCK_RE=/^(unix:\/[^\s;{}]+|\d{1,3}(\.\d{1,3}){3}:\d{1,5})$/i;
  var SIZE_RE=/^\d+[kKmMgG]?$/;
  var errors=[];
  var host=hostRaw||'example.com';
  if(hostRaw && !HOST_RE.test(host)) errors.push('Server name: use a valid hostname (e.g. example.com) - no paths, quotes or semicolons.');
  var sock=gv('php_sock').trim();
  if(sock && !SOCK_RE.test(sock)) errors.push('PHP-FPM socket: use unix:/run/php/php8.3-fpm.sock or 127.0.0.1:9000 - no ; } or directives.');
  var bsize=gv('body_size').trim();
  if(bsize && !SIZE_RE.test(bsize)) errors.push('client_max_body_size: use a plain size like 64M or 128M.');
  if(errors.length){
    inputError(errors.join(' '));
    var L=['# CONFIG NOT GENERATED - fix the highlighted inputs first:'];
    errors.forEach(function(e){ L.push('# - '+e); });
    return L.join('\n');
  }
  clearInputError();
  var httpsOn=(gv('ssl_mode')!=='none');
  var forceHTTPS=httpsOn && chk('force_https');
  var L=[];
  L.push('# BEGIN GWill Nginx - WordPress server block - '+date);
  L.push('# Generated by ngx·min. Test with `nginx -t` before reloading. Safe to re-run.');
  L.push('# server_name: '+host);
  L.push('');

  /* ---- :80 plain/redirect server block (always present when HTTP allowed) ---- */
  {
    L.push('# BEGIN GWill Nginx - http (port 80) server - '+date);
    L.push('server {');
    L.push('  listen 80;');
    L.push('  listen [::]:80;');
    L.push('  server_name '+gv('server_name')+';');
    if(forceHTTPS){
      L.push('  # Force HTTPS: canonical redirect, no if{} needed');
      L.push('  return 301 https://$host$request_uri;');
      L.push('}');
      L.push('# END GWill Nginx - http (port 80) server');
      L.push('');
    }else{
      L.push('  root /var/www/html;');
      L.push('  index index.php index.html;');
      pushHttpServer(L, pv, forceHTTPS, date, host);
      L.push('}');
      L.push('# END GWill Nginx - http (port 80) server');
      L.push('');
    }
  }

  /* ---- 443 ssl server block (only when SSL mode !== none) ---- */
  if(httpsOn){
    L.push('# BEGIN GWill Nginx - https (port 443) server - '+date);
    L.push('server {');
    L.push('  listen 443 ssl http2;');
    L.push('  listen [::]:443 ssl http2;');
    L.push('  server_name '+gv('server_name')+';');
    L.push('  root /var/www/html;');
    L.push('  index index.php index.html;');
    L.push('');
    L.push('  # --- TLS ---');
    L.push('  ssl_certificate     /etc/letsencrypt/live/'+gv('server_name')+'/fullchain.pem;');
    L.push('  ssl_certificate_key /etc/letsencrypt/live/'+gv('server_name')+'/privkey.pem;');
    if(gv('ssl_mode')==='selfsigned'){
      L.push('  # self-signed: point the two lines above at your own cert/key');
    }
    L.push('  ssl_protocols TLSv1.2 TLSv1.3;');
    L.push('  ssl_ciphers ECDHE-ECDSA-AES128-GCM-SHA256:ECDHE-RSA-AES128-GCM-SHA256:ECDHE-ECDSA-AES256-GCM-SHA384:ECDHE-RSA-AES256-GCM-SHA384:ECDHE-ECDSA-CHACHA20-POLY1305:ECDHE-RSA-CHACHA20-POLY1305:DHE-RSA-AES128-GCM-SHA256:DHE-RSA-AES256-GCM-SHA384;');
    L.push('  ssl_prefer_server_ciphers on;');
    L.push('  ssl_session_cache shared:SSL:10m;');
    L.push('  ssl_session_timeout 10m;');
    L.push('  # ssl_stapling on;            # OCSP stapling - enable if your cert supports it');
    L.push('  # ssl_stapling_verify on;');
    L.push('');
    L.push('  # --- security headers (443 block only - add_header would be dropped by an include) ---');
    if(chk('sec_headers')){
      L.push('  add_header X-Content-Type-Options "nosniff" always;');
      L.push('  add_header X-Frame-Options "SAMEORIGIN" always;');
      L.push('  add_header X-XSS-Protection "1; mode=block" always; # legacy - kept for older browsers');
      L.push('  add_header Referrer-Policy "strict-origin-when-cross-origin" always;');
      L.push('  add_header Permissions-Policy "camera=(), geolocation=(), microphone=(), payment=()" always;');
      L.push('  add_header Strict-Transport-Security "max-age=31536000; includeSubDomains" always; # HSTS - only valid here on HTTPS');
    }
    pushHttpServer(L, pv, forceHTTPS, date, host);
    L.push('}');
    L.push('# END GWill Nginx - https (port 443) server');
  }

  while(L.length && L[L.length-1]==='')L.pop();
  return L.join('\n')+'\n';
}

/* shared location blocks + server-level directives that belong in the serving server block */
function pushHttpServer(L, pv, forceHTTPS, date, host){
  var p=preset();
  L.push('');
  L.push('  # --- server-level tuning ---');
  if(p==='free'){
    L.push('  # worker_processes/worker_connections are set in nginx.conf, not here.');
    L.push('  # Free-tier VPS (~512MB - 1GB): keep Nginx modest. No Redis / memcached below  - ');
    L.push('  # a comment in cache-presets explains why. A slow plugin should not hard-504:');
    L.push('  fastcgi_connect_timeout 30s;');
    L.push('  fastcgi_send_timeout '+Math.min(pv.fcgiTimeout,30)+'s;');
    L.push('  fastcgi_read_timeout '+(gv('read_timeout')?parseInt(gv('read_timeout'),10)+'s':(Math.min(pv.fcgiTimeout,30)+'s'))+';');
    L.push('  # Raise these to 60-120s on a bigger box (see the Standard preset).');
  }else if(p==='std'){
    L.push('  # Standard preset - comfortable 1-2GB. Generous timeouts for slow plugins.');
    L.push('  fastcgi_connect_timeout 60s;');
    L.push('  fastcgi_send_timeout 60s;');
    L.push('  fastcgi_read_timeout '+(gv('read_timeout')?parseInt(gv('read_timeout'),10)+'s':'60s')+';');
  }else{
    L.push('  # Performance preset - 2GB+ with a real cache.');
    L.push('  fastcgi_connect_timeout 120s;');
    L.push('  fastcgi_send_timeout 120s;');
    L.push('  fastcgi_read_timeout '+(gv('read_timeout')?parseInt(gv('read_timeout'),10)+'s':'120s')+';');
  }
  L.push('  client_max_body_size '+gv('body_size')+';');
  L.push('  # WP upload limits (upload_max_filesize / post_max_size) are PHP-side, not Nginx.');
  L.push('');

  if(chk('gzip')){
    L.push('  # BEGIN GWill Nginx - gzip - '+date);
    L.push('  gzip on;');
    L.push('  gzip_vary on;');
    L.push('  gzip_min_length 1024;');
    L.push('  gzip_comp_level 5;');
    L.push('  gzip_types text/plain text/css text/html application/javascript application/json application/xml image/svg+xml;');
    L.push('  # END GWill Nginx - gzip');
    L.push('');
  }

  /* comment-spam / xmlrpc deny */
  if(chk('comments_spam')){
    L.push('  # BEGIN GWill Nginx - comment spam / XML-RPC - '+date);
    L.push('  # Deny POST to wp-comments-post from non-referrers, and block xmlrpc.php outright.');
    L.push('  location = /xmlrpc.php {');
    L.push('    deny all;');
    L.push('    access_log off;');
    L.push('    return 403;');
    L.push('  }');
    L.push('  location = /wp-comments-post.php {');
    L.push('    if ($http_referer !~ "^https?://([^/]+\\.)*'+escRe(host)+'(?::\\d+)?(/|$)") { return 403; }');
    L.push('  }');
    L.push('  # END GWill Nginx - comment spam / XML-RPC');
    L.push('');
  }

  /* static cache */
  if(chk('static_cache')){
    L.push('  # BEGIN GWill Nginx - static asset caching - '+date);
    L.push('  location ~* \\.(jpg|jpeg|png|gif|ico|css|js|webp|svg|woff2)$ {');
    L.push('    expires 30d;');
    L.push('    add_header Cache-Control "public, max-age=2592000, immutable" always;');
    L.push('    access_log off;');
    L.push('  }');
    L.push('  # END GWill Nginx - static asset caching');
    L.push('');
  }

  /* basic auth placeholder */
  if(chk('basic_auth')){
    L.push('  # BEGIN GWill Nginx - basic auth (wp-admin placeholder) - '+date);
    L.push('  # Generate a password file: htpasswd -c /etc/nginx/.htpasswd myuser');
    L.push('  # location /wp-admin/ {');
    L.push('  #   auth_basic "Restricted";');
    L.push('  #   auth_basic_user_file /etc/nginx/.htpasswd;');
    L.push('  #   try_files $uri $uri/ /index.php?$args;');
    L.push('  # }');
    L.push('  # END GWill Nginx - basic auth');
    L.push('');
  }

  /* rate limit placeholder */
  if(chk('rate_limit')){
    L.push('  # BEGIN GWill Nginx - rate / conn limit (commented) - '+date);
    L.push('  # Put in http{} context:');
    L.push('  #   limit_req_zone $binary_remote_addr zone=wp_req:10m rate=10r/s;');
    L.push('  #   limit_conn_zone $binary_remote_addr zone=wp_conn:10m;');
    L.push('  # Then in this location:');
    L.push('  #   limit_req zone=wp_req burst=20 nodelay;');
    L.push('  #   limit_conn wp_conn 10;');
    L.push('  # END GWill Nginx - rate / conn limit');
    L.push('');
  }

  /* fastcgi cache */
  if(chk('fcgi_cache')){
    L.push('  # BEGIN GWill Nginx - FastCGI cache - '+date);
    L.push('  # fastcgi_cache_path belongs in the http{} context (not a server block):');
    L.push('  #   fastcgi_cache_path /var/run/nginx-fastcgi/wp levels=1:2 keys_zone=wp:'+pv.cacheZone+' inactive='+pv.cacheInactive+' max_size='+pv.cacheMaxSize+';');
    L.push('  set $skip_cache 0;');
    L.push('  # Don\'t cache POSTs, query strings, raw feeds, sitemaps, or the back-end');
    L.push('  if ($request_method = POST) { set $skip_cache 1; }');
    L.push('  if ($query_string != "") { set $skip_cache 1; }');
    L.push('  if ($request_uri ~* "/wp-admin/|/wp-json/|/wp-.+\\.php") { set $skip_cache 1; }');
    L.push('  if ($http_cookie ~* "wordpress_logged_in_|wp-settings-") { set $skip_cache 1; }');
    L.push('  # END GWill Nginx - FastCGI cache (skip rules)');
    L.push('');
  }

  if(chk('fcgi_cache')){
    L.push('  # BEGIN GWill Nginx - PHP-FPM with FastCGI cache - '+date);
  }else{
    L.push('  # BEGIN GWill Nginx - PHP-FPM - '+date);
  }
  L.push('  location ~ \\.php$ {');
  L.push('    try_files $uri =404;');
  L.push('    fastcgi_pass '+gv('php_sock')+';');
  L.push('    fastcgi_index index.php;');
  L.push('    include fastcgi_params;');
  L.push('    fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;');
  if(chk('fcgi_cache')){
    L.push('    # FastCGI cache - comment ALL of these lines out is WRONG; instead uncomment ALL of them');
    L.push('    # TOGETHER WITH the fastcgi_cache_path line in http{} (above), then nginx -t.');
    L.push('    # fastcgi_cache_bypass $skip_cache;');
    L.push('    # fastcgi_no_cache $skip_cache;');
    L.push('    # fastcgi_cache wp;');
    L.push('    # fastcgi_cache_valid 200 301 302 60m;');
    L.push('    # fastcgi_cache_valid 404 1m;');
    L.push('    # fastcgi_cache_key $scheme$request_method$host$request_uri;');
    L.push('    # fastcgi_cache_use_stale error timeout updating;');
    L.push('    # fastcgi_ignore_headers Cache-Control Expires Set-Cookie;');
  }
  L.push('  }');
  L.push('  # END GWill Nginx - PHP-FPM');
  L.push('');

  L.push('  # BEGIN GWill Nginx - WordPress permalinks - '+date);
  L.push('  location / {');
  L.push('    try_files $uri $uri/ /index.php?$args;');
  L.push('  }');
  L.push('  # END GWill Nginx - WordPress permalinks');
}

/* ---------- render ---------- */
function escapeHtml(s){return String(s).replace(/[&<>]/g,function(c){return {'&':'&amp;','<':'&lt;','>':'&gt;'}[c];});}
function render(txt){
  txt = (txt === undefined || txt === null) ? '' : txt;
  currentText=txt; window.__ngx_text=txt;
  var lines=txt.split('\n'); var html='';
  for(var i=0;i<lines.length;i++){
    var line=lines[i], t=line.trim();
    if(t===''){ html+='<code>&nbsp;</code>\n'; continue; }
    if(t.charAt(0)==='#'){ html+='<code class="cmt">'+escapeHtml(line)+'</code>\n'; continue; }
    var esc=escapeHtml(line);
    var out=esc.replace(/[{}]/g,function(x){return '<span class="brace">'+x+'</span>';});
    var kw=line.match(/^(\s*)([A-Za-z][A-Za-z0-9_]*)/);
    if(kw){ out=out.replace(new RegExp('^('+escRe(kw[1])+escRe(kw[2])+')'),'<span class="kw">$1</span>'); }
    out=out.replace(/(&quot;[^&]*&quot;|[.;:][^<]*?;)/g,function(m){return '<span class="str">'+m+'</span>';});
    html+='<code>'+out+'</code>\n';
  }
  preview.innerHTML=html;
  byteCount.textContent=String(txt.length)+' B';
}
function update(){ render(build()); }

/* ---------- copy / download ---------- */
function copyText(t){
  if(navigator.clipboard&&navigator.clipboard.writeText){
    navigator.clipboard.writeText(t).then(function(){flash(copyBtn,'Copied ✓');},function(){fallbackCopy(t);});
  }else fallbackCopy(t);
}
function fallbackCopy(t){
  var ta=document.createElement('textarea');ta.value=t;ta.style.position='fixed';ta.style.opacity='0';document.body.appendChild(ta);
  ta.focus();ta.select();
  try{document.execCommand('copy');flash(copyBtn,'Copied ✓');}catch(e){flash(copyBtn,'copy failed');}
  document.body.removeChild(ta);
}
function flash(btn,label){var old=btn.textContent;btn.textContent=label;setTimeout(function(){btn.textContent=old;},1400);}
function download(){
  var blob=new Blob([currentText],{type:'text/plain'});
  var url=URL.createObjectURL(blob);
  var a=document.createElement('a');a.href=url;a.download='wordpress-server.conf';document.body.appendChild(a);a.click();
  setTimeout(function(){URL.revokeObjectURL(url);a.remove();},400);
}

/* ---------- events ---------- */
(function(){
  var deb=null;
  function wire(){
    Array.prototype.forEach.call(document.querySelectorAll('input[type=checkbox], input[type=radio], select'),function(el){
      el.addEventListener('change',update);
    });
    Array.prototype.forEach.call(document.querySelectorAll('input[type=text], input[type=number], textarea'),function(el){
      el.addEventListener('input',function(){ if(deb)clearTimeout(deb); deb=setTimeout(update,160); });
    });
    copyBtn.addEventListener('click',function(){copyText(currentText);});
    dlBtn.addEventListener('click',download);
  }
  wire();
  update();
})();
})();
