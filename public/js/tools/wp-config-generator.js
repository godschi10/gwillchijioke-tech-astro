/* ============================================================
   wp-config.php Generator + (SQLite + Hardening edition) - v1.19.82
   Builds a complete wp-config.php in the browser: DB type (MySQL OR
   SQLite), 8 auth salts generated client-side with crypto.getRandomValues,
   debug/perf constants, free-tier hardening. Nothing leaves the device.

   SQLite constants are AUTHORITATIVE - read from the installed
   sqlite-database-integration/constants.php (v3):
     DB_ENGINE = 'sqlite' (auto via SQLITE_DB_DROPIN_VERSION)
     DB_DIR    = wp-content/database (default, FQDBDIR)
     DB_FILE   = .ht.sqlite           (default, FQDB)
   So we emit DB_ENGINE + DB_DIR + DB_FILE so the user controls the file.
   Scoped under #wpc-app; classes prefixed wpc-.
   ------------------------------------------------------------ */
(function () {
  'use strict';
  function $(id) { return document.getElementById(id); }
  var out = $('wpc-out'), byteCount = $('wpc-byteCount'),
      dbSel = $('wpc-db'), dbHost = $('wpc-dbHost'), dbName = $('wpc-dbName'),
      dbUser = $('wpc-dbUser'), dbPass = $('wpc-dbPass'),
      dbPrefix = $('wpc-prefix'), dbCharset = $('wpc-charset'),
      collapse = $('wpc-collate'), lang = $('wpc-lang'),
      memLimit = $('wpc-memlimit'), maxMem = $('wpc-maxmem'),
      debug = $('wpc-debug'), debugLog = $('wpc-debuglog'), debugDisplay = $('wpc-debugdisplay'),
      scriptDebug = $('wpc-scriptdebug'), saveQueries = $('wpc-savequeries'),
      disallowEditor = $('wpc-disfileedit'), disallowMods = $('wpc-disfilemods'),
      autoUpdates = $('wpc-autoupdates'), revisions = $('wpc-revisions'),
      autosave = $('wpc-autosave'), cron = $('wpc-cron'), fsMethod = $('wpc-fsmethod'),
      sqliteEngine = $('wpc-sqlite'),
      copyBtn = $('wpc-copy'), dlBtn = $('wpc-dl'), regenBtn = $('wpc-regen'), msg = $('wpc-msg');

  /* ---------- CSPRNG salts (public-domain wp_salt format: 64 chars random) ---------- */
  var SALT_CHARS = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!@#$%^&*()-_=+[]{};:,.?/~`\'"';
  function randInt(max) {
    var maxUint = 0xFFFFFFFF, limit = maxUint - (maxUint % max), arr = new Uint32Array(1), x;
    do { crypto.getRandomValues(arr); x = arr[0]; } while (x >= limit);
    return x % max;
  }
  function genSalt() {
    var s = '';
    for (var i = 0; i < 64; i++) s += SALT_CHARS[randInt(SALT_CHARS.length)];
    return s;
  }
  function genSalts() {
    return {
      auth: genSalt(), secureAuth: genSalt(), loggedIn: genSalt(), nonce: genSalt(),
      authSalt: genSalt(), secureAuthSalt: genSalt(), loggedInSalt: genSalt(), nonceSalt: genSalt()
    };
  }
  var salts = genSalts();

  /* ---------- helpers ---------- */
  function showMsg(t, k) { msg.textContent = t; msg.className = 'wpc-msg' + (k ? ' ' + k : ''); msg.hidden = false; }
  function clearMsg() { msg.hidden = true; }
  function phpStr(v) { // escape a PHP single-quoted string
    return String(v == null ? '' : v).replace(/\\/g, '\\\\').replace(/'/g, "\\'");
  }
  function fmtBytes(n) { return n >= 1024 ? (n / 1024).toFixed(1) + ' KB' : n + ' B'; }

  /* ---------- build the wp-config.php ---------- */
  function build() {
    var isSqlite = !!sqliteEngine.checked;
    var L = [];
    L.push('<?php');
    L.push('/**');
    L.push(' * WordPress wp-config.php');
    L.push(' * Generated by GWill wp-config.php Generator (SQLite + Hardening Edition)');
    L.push(' * https://tech.gwillchijioke.com/tools/wp-config-generator/');
    L.push(' * Safe to re-run through the generator; keep this header + your salts.');
    L.push(' */');
    L.push('');

    /* --- DB type: SQLite (the moat) or MySQL --- */
    if (isSqlite) {
      L.push('/* =======================================================');
      L.push('   SQLite Database Integration (the moat).');
      L.push('   The plugin reads these constants from wp-config.php:');
      L.push('     DB_ENGINE  -> "sqlite"  (auto-detected from the drop-in)');
      L.push('     DB_DIR     -> the directory holding the .sqlite file');
      L.push('     DB_FILE    -> the database file name');
      L.push('   Defaults: FQDBDIR = wp-content/database/, FQDB = .ht.sqlite');
      L.push('   Requires the sqlite-database-integration drop-in (db.php).');
      L.push('   ------------------------------------------------------- */');
      // WordPress core still wants DB_NAME; the SQLite plugin tolerates it.
      L.push("define( 'DB_NAME', '" + phpStr(dbName.value || 'wordpress_sqlite') + "' );");
      L.push("define( 'DB_HOST', 'localhost' );");  // ignored by SQLite, harmless
      // Authoritative DB_DIR / DB_FILE (from constants.php)
      var dir = (dbName.value === 'wordpress_sqlite' || !$('wpc-dbDir').value)
        ? "WP_CONTENT_DIR . '/database'" : "'" + phpStr($('wpc-dbDir').value) + "'";
      L.push('define( \'DB_DIR\', ' + dir + ' );   // <- the database folder');
      var file = $('wpc-dbFile').value || '.ht.sqlite';
      L.push("define( 'DB_FILE', '" + phpStr(file) + "' );  // <- the .sqlite file");
      L.push("define( 'DB_CHARSET', '" + phpStr(dbCharset.value || 'utf8') + "' );");
      L.push("define( 'DB_COLLATE', '' );");
      L.push(''); // SQLite needs no DB_USER/DB_PASSWORD
    } else {
      L.push("define( 'DB_NAME', '" + phpStr(dbName.value || 'wordpress') + "' );");
      L.push("define( 'DB_USER', '" + phpStr(dbUser.value || 'wp_user') + "' );");
      L.push("define( 'DB_PASSWORD', '" + phpStr(dbPass.value) + "' );");
      L.push("define( 'DB_HOST', '" + phpStr(dbHost.value || 'localhost') + "' );");
      L.push("define( 'DB_CHARSET', '" + phpStr(dbCharset.value || 'utf8') + "' );");
      L.push("define( 'DB_COLLATE', '" + phpStr(collapse.value || '') + "' );");
      L.push('');
    }

    /* --- table prefix --- */
    var prefix = $('wpc-prefix').value || 'wp_';
    L.push('/**#@+');
    L.push(' * WP table prefix.');
    L.push(' */');
    L.push("$table_prefix = '" + phpStr(prefix) + "';");
    L.push('');

    /* --- salts --- */
    L.push('/**#@+');
    L.push(' * Authentication unique keys + salts.');
    L.push(' * Generated client-side with crypto.getRandomValues - never reused,');
    L.push(' * never sent anywhere. Change them to invalidate all sessions.');
    L.push(' */');
    L.push("define( 'AUTH_KEY',         '" + phpStr(salts.auth) + "' );");
    L.push("define( 'SECURE_AUTH_KEY',  '" + phpStr(salts.secureAuth) + "' );");
    L.push("define( 'LOGGED_IN_KEY',    '" + phpStr(salts.loggedIn) + "' );");
    L.push("define( 'NONCE_KEY',        '" + phpStr(salts.nonce) + "' );");
    L.push("define( 'AUTH_SALT',        '" + phpStr(salts.authSalt) + "' );");
    L.push("define( 'SECURE_AUTH_SALT', '" + phpStr(salts.secureAuthSalt) + "' );");
    L.push("define( 'LOGGED_IN_SALT',   '" + phpStr(salts.loggedInSalt) + "' );");
    L.push("define( 'NONCE_SALT',       '" + phpStr(salts.nonceSalt) + "' );");
    L.push('/**#@-*/');
    L.push('');

    /* --- debug --- */
    L.push("define( 'WP_DEBUG', " + (debug.checked ? 'true' : 'false') + " );");
    if (debug.checked) {
      L.push("define( 'WP_DEBUG_LOG', " + (debugLog.checked ? 'tru' + 'e' : 'false') + " );");
      L.push("define( 'WP_DEBUG_DISPLAY', " + (debugDisplay.checked ? 'tru' + 'e' : 'false') + " );");
    }
    if (scriptDebug.checked) L.push("define( 'SCRIPT_DEBUG', true );");
    if (saveQueries.checked) L.push("define( 'SAVEQUERIES', true );");
    L.push("define( 'WP_ENVIRONMENT_TYPE', 'production' );");
    L.push('');

    /* --- perf / hardening --- */
    L.push("define( 'WP_MEMORY_LIMIT', '" + phpStr(memLimit.value || '64M') + "' );");
    L.push("define( 'WP_MAX_MEMORY_LIMIT', '" + phpStr(maxMem.value || '256M') + "' );");
    if (disallowEditor.checked) L.push("define( 'DISALLOW_FILE_EDIT', true );  // no in-dashboard code editing (free-tier hardening)");
    if (disallowMods.checked) L.push("define( 'DISALLOW_FILE_MODS', true );");
    if (autoUpdates.checked) L.push("define( 'AUTOMATIC_UPDATER_DISABLED', true );");
    if (revisions.value) L.push("define( 'WP_POST_REVISIONS', " + parseInt(revisions.value, 10) + " );");
    if (autosave.value) L.push("define( 'AUTOSAVE_INTERVAL', " + parseInt(autosave.value, 10) + " );");
    if (cron.checked) L.push("define( 'DISABLE_WP_CRON', true );  // free-tier: use a real cron job");
    if (fsMethod.value) L.push("define( 'FS_METHOD', '" + phpStr(fsMethod.value) + "' );");
    L.push('');

    /* --- language / timezone --- */
    if (lang.value) L.push("define( 'WPLANG', '" + phpStr(lang.value) + "' );");
    L.push("define( 'WP_SITEURL', 'https://' + $_SERVER['HTTP_HOST'] );");
    L.push("define( 'WP_HOME', 'https://' + $_SERVER['HTTP_HOST'] );");
    L.push('');

    /* --- debug log path (free-tier friendly) --- */
    L.push('/* If you turn WP_DEBUG_LOG on, logs land here (keeps the web dir clean): */');
    L.push("define( 'WP_DEBUG_LOG', WP_CONTENT_DIR . '/debug.log' );");
    L.push("define( 'WP_DEBUG_DISPLAY', false );");
    L.push('');

    /* --- wp-content override (optional) --- */
    L.push('/* Custom wp-content directory (optional - uncomment if you relocate it): */');
    L.push('// define( \'WP_CONTENT_DIR\', dirname( __FILE__ ) . \'/wp-content\' );');
    L.push('// define( \'WP_CONTENT_URL\', \'https://\' . $_SERVER[\'HTTP_HOST\'] . \'/wp-content\' );');
    L.push('');

    /* --- config path (the SQLite plugin needs wp-content to be writable for db.php) --- */
    L.push('/* Absolute path to the WordPress directory. */');
    L.push("if ( ! defined( 'ABSPATH' ) ) {");
    L.push("\tdefine( 'ABSPATH', __DIR__ . '/' );");
    L.push('}');
    L.push('');
    L.push('/* Sets up WordPress vars + included files. */');
    L.push("require_once ABSPATH . 'wp-settings.php';");
    L.push('');

    var text = L.join('\n');
    // clean double-blank lines
    text = text.replace(/\n{3,}/g, '\n\n');
    return text;
  }

  /* ---------- render preview with simple comment/string coloring ---------- */
  function esc(s) { return String(s).replace(/[&<>]/g, function (c) { return { '&': '&amp;', '<': '&lt;', '>': '&gt;' }[c]; }); }
  function render(text) {
    var html = text.split('\n').map(function (line) {
      var t = line.trim();
      if (t === '') return '<code>&nbsp;</code>';
      if (t.charAt(0) === '#') return '<code class="cmt">' + esc(line) + '</code>';
      if (t.indexOf('/*') === 0 || t.indexOf(' *') === 0 || t.indexOf('*/') === 0) return '<code class="cmt">' + esc(line) + '</code>';
      if (t.indexOf('//') === 0 || t.indexOf('/*') >= 0) { // inline comment tail
        var m = line.indexOf('//');
        if (m > 0) return '<code>' + esc(line.slice(0, m)) + '<span class="cmt">' + esc(line.slice(m)) + '</span></code>';
        if (line.indexOf('/*') >= 0) { var m2 = line.indexOf('/*'); return '<code>' + esc(line.slice(0, m2)) + '<span class="cmt">' + esc(line.slice(m2)) + '</span></code>'; }
        return '<code class="cmt">' + esc(line) + '</code>';
      }
      var d = line.match(/^(\s*)(?:define\s*\()?(\$table_prefix|\w+)/);
      var out = esc(line);
      if (d && (d[2] === 'define' || d[2] === '$table_prefix' || /^define\s*\(/.test(t))) {
        out = esc(line).replace(/^(\s*)(define\s*\(|&\$table_prefix)/, '<span class="kw">$2</span>');
      }
      return '<code>' + out + '</code>';
    }).join('\n');
    out.innerHTML = html;
    byteCount.textContent = fmtBytes(text.length);
    out.setAttribute('data-raw', text);
    window.__wpc_text = text;
  }

  /* ---------- updates ---------- */
  function update() {
    var isSqlite = !!sqliteEngine.checked;
    dbSel.value = isSqlite ? 'sqlite' : 'mysql';
    // switch visible DB fields
    if ($('wpc-mysqlFields')) $('wpc-mysqlFields').hidden = isSqlite;
    if ($('wpc-sqliteFields')) $('wpc-sqliteFields').hidden = !isSqlite;
    render(build());
  }

  /* ---------- copy / download ---------- */
  function copyText(t) {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      navigator.clipboard.writeText(t).then(function () { flash(copyBtn, 'Copied ✓'); }, function () { fallbackCopy(t); });
    } else fallbackCopy(t);
  }
  function fallbackCopy(t) {
    var ta = document.createElement('textarea'); ta.value = t; ta.style.position = 'fixed'; ta.style.opacity = '0';
    document.body.appendChild(ta); ta.focus(); ta.select();
    try { document.execCommand('copy'); flash(copyBtn, 'Copied ✓'); } catch (e) { flash(copyBtn, 'copy failed', 'err'); }
    document.body.removeChild(ta);
  }
  function flash(btn, label, k) { var old = btn.textContent; btn.textContent = label; setTimeout(function () { btn.textContent = old; }, 1400); }
  function download() {
    var blob = new Blob([window.__wpc_text || ''], { type: 'text/php' });
    var url = URL.createObjectURL(blob);
    var a = document.createElement('a'); a.href = url; a.download = 'wp-config.php'; document.body.appendChild(a); a.click();
    setTimeout(function () { URL.revokeObjectURL(url); a.remove(); }, 400);
  }

  /* ---------- events ---------- */
  if (sqliteEngine) sqliteEngine.addEventListener('change', update);
  if (dbSel) dbSel.addEventListener('change', function () { sqliteEngine.checked = dbSel.value === 'sqlite'; update(); });
  if (regenBtn) regenBtn.addEventListener('click', function () { salts = genSalts(); update(); });
  if (copyBtn) copyBtn.addEventListener('click', function () { copyText(window.__wpc_text || ''); });
  if (dlBtn) dlBtn.addEventListener('click', download);
  var deb = null;
  Array.prototype.forEach.call(document.querySelectorAll('.wpc-in, .wpc-in-chk'), function (el) {
    el.addEventListener('input', function () { if (deb) clearTimeout(deb); deb = setTimeout(update, 150); });
    el.addEventListener('change', function () { if (deb) clearTimeout(deb); deb = setTimeout(update, 150); });
  });

  /* ---------- init ---------- */
  update();
})();
